<#
  Build a signed, standalone "Seen It" release APK for sideloading.

  Usage (from repo root):   npm run apk
  Output:                   .\SeenIt-v<versionCode>.apk

  Prerequisites (already true on this machine):
    - JDK 17 (JAVA_HOME set)
    - Android SDK at C:\Android\Sdk
    - The release keystore restored at android\app\seenit-release.keystore
      (backup lives in .\credentials\ — see credentials\README.md)

  To ship an UPDATE: bump versionCode in app.json (android.versionCode) AND
  android\app\build.gradle (versionCode + versionName), then run this. The user
  installs the new APK over the old one (tap -> Update) with no data loss, because
  it is signed with the same seenit-release.keystore.

  JS-only changes don't need a new APK: publish an OTA instead (README ->
  "Shipping updates"). A new APK is only needed for native changes (new native
  module, SDK upgrade, native config) — and those also need a new runtimeVersion
  in app.json, so OTAs built for the new APK never reach older ones.
#>
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
Set-Location $repo

# Restore the release keystore into android/app if it's missing (e.g. android/ was regenerated).
$ks = 'android\app\seenit-release.keystore'
if (-not (Test-Path $ks)) {
  if (Test-Path 'credentials\seenit-release.keystore') {
    Copy-Item 'credentials\seenit-release.keystore' $ks -Force
    Write-Host "Restored release keystore from credentials\." -ForegroundColor Yellow
  } else {
    throw "Release keystore missing and no backup in credentials\. Cannot sign the APK."
  }
}

# Point Gradle at the Android SDK.
if (-not $env:ANDROID_HOME) { $env:ANDROID_HOME = 'C:\Android\Sdk' }
$env:ANDROID_SDK_ROOT = $env:ANDROID_HOME

# Re-derive the expo-updates (EAS Update) native config from app.json every build,
# so the installed APK's runtime version / update URL / channel can never drift
# from what OTA updates are published against. Safe + idempotent; leaves signing
# untouched. (Our android/ is persisted and not regenerated by prebuild.)
Write-Host "Syncing expo-updates native config from app.json..." -ForegroundColor Cyan
& npx expo-updates configuration:syncnative --platform android --workflow generic
if ($LASTEXITCODE -ne 0) { throw "expo-updates configuration:syncnative failed (exit $LASTEXITCODE)." }

# Read versionCode so we can name the artifact.
$gradle = Get-Content 'android\app\build.gradle' -Raw
$versionCode = ([regex]::Match($gradle, 'versionCode\s+(\d+)')).Groups[1].Value
if (-not $versionCode) { $versionCode = 'x' }

# Force a fresh embedded update manifest (id + commitTime) on every build. The
# expo-updates Gradle task only declares string inputs, so on our persisted android/
# Gradle treats it as up-to-date forever and the APK would ship an OLD commitTime.
# expo-updates launches the newest update by commitTime, so any OTA published after
# that stale stamp would replace this build's JS from the second launch, even when
# the OTA's code is older than the build. `--rerun` forces the task; the check after
# the build verifies the result.
$buildStartMs = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()

Write-Host "Building Seen It release APK (versionCode $versionCode)..." -ForegroundColor Cyan
Push-Location android
try {
  & .\gradlew.bat :app:createReleaseUpdatesResources --rerun assembleRelease
  if ($LASTEXITCODE -ne 0) { throw "Gradle build failed (exit $LASTEXITCODE)." }
} finally {
  Pop-Location
}

$built = 'android\app\build\outputs\apk\release\app-release.apk'
if (-not (Test-Path $built)) { throw "Build reported success but APK not found at $built." }

# Fail loudly — before replacing the deliverable — if this build didn't embed a
# freshly generated update manifest.
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead((Resolve-Path $built).Path)
try {
  $entry = $zip.GetEntry('assets/app.manifest')
  if (-not $entry) { throw "The APK has no embedded update manifest (assets/app.manifest)." }
  $reader = New-Object IO.StreamReader($entry.Open())
  try { $manifest = $reader.ReadToEnd() | ConvertFrom-Json } finally { $reader.Dispose() }
} finally {
  $zip.Dispose()
}
if ([int64]$manifest.commitTime -lt ($buildStartMs - 1000)) {
  $stamp = [DateTimeOffset]::FromUnixTimeMilliseconds([int64]$manifest.commitTime).ToLocalTime()
  throw "Embedded update manifest is stale (commitTime $stamp predates this build) - OTAs published since then would replace this APK's JS."
}

$out = "SeenIt-v$versionCode.apk"
Copy-Item $built $out -Force
$mb = [math]::Round((Get-Item $out).Length / 1MB, 1)
$embeddedAt = [DateTimeOffset]::FromUnixTimeMilliseconds([int64]$manifest.commitTime).ToLocalTime()
Write-Host ""
Write-Host "APK ready: $repo\$out ($mb MB)" -ForegroundColor Green
Write-Host "Embedded update $($manifest.id), created $embeddedAt (newer OTAs still apply)."
Write-Host "Send this file to the phone, tap it, choose Update (do NOT uninstall)."
